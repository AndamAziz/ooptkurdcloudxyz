-- EnglishMaster AI — question bank and server-scored practice.
--
-- * Students never read assessment_questions directly: answer keys stay on the server.
--   They download question content (without keys) via get_practice_questions().
-- * Answers are submitted via submit_practice_response(), which scores on the server.
--   The call is idempotent on the client-generated response id, so an offline queue
--   can retry safely. If the same question is answered twice in one attempt, the
--   first stored answer wins and is returned to the caller.

create table public.assessment_questions (
  id             uuid primary key default gen_random_uuid(),
  external_ref   text unique,
  cefr_level     public.cefr_level not null,
  skill          text not null check (skill in ('grammar', 'vocabulary', 'reading', 'listening')),
  question_type  text not null default 'mcq_single' check (question_type in ('mcq_single')),
  prompt         text not null check (char_length(prompt) between 1 and 2000),
  options        text[] not null check (cardinality(options) between 2 and 6),
  correct_option text not null check (correct_option ~ '^[A-F]$'),
  explanation    text check (char_length(explanation) <= 2000),
  tags           text[] not null default '{}',
  version        integer not null default 1 check (version >= 1),
  status         text not null default 'draft' check (status in ('draft', 'published', 'retired')),
  review_status  text not null default 'unreviewed' check (review_status in ('unreviewed', 'approved')),
  source         text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  check (ascii(correct_option) - ascii('A') < cardinality(options))
);
comment on table public.assessment_questions is
  'Question bank incl. answer keys. Teachers/admins read; students use get_practice_questions(). review_status=unreviewed marks content not yet checked by a teacher.';
comment on column public.assessment_questions.version is
  'Bump when prompt/options/key change so stored responses keep the version they were scored against.';
create index assessment_questions_level_idx on public.assessment_questions (cefr_level, status, id);

create trigger assessment_questions_touch_updated_at
  before update on public.assessment_questions
  for each row execute function private.touch_updated_at();

create table public.assessment_attempts (
  id                uuid primary key,
  user_id           uuid not null references auth.users (id) on delete cascade,
  kind              text not null check (kind in ('practice')),
  cefr_level        public.cefr_level not null,
  status            text not null default 'in_progress' check (status in ('in_progress', 'completed')),
  client_started_at timestamptz,
  created_at        timestamptz not null default now(),
  completed_at      timestamptz
);
comment on table public.assessment_attempts is
  'One practice (later: placement) session. id is generated by the client so offline sessions sync idempotently.';
create index assessment_attempts_user_idx on public.assessment_attempts (user_id, created_at desc);

create table public.assessment_responses (
  id                 uuid primary key,
  attempt_id         uuid not null references public.assessment_attempts (id) on delete cascade,
  user_id            uuid not null references auth.users (id) on delete cascade,
  question_id        uuid not null references public.assessment_questions (id) on delete restrict,
  question_version   integer not null,
  chosen_option      text not null check (chosen_option ~ '^[A-F]$'),
  is_correct         boolean not null,
  client_answered_at timestamptz,
  received_at        timestamptz not null default now(),
  unique (attempt_id, question_id)
);
comment on table public.assessment_responses is
  'Server-scored answers. is_correct and received_at are set by the server; client_answered_at is informational only.';
create index assessment_responses_user_idx on public.assessment_responses (user_id, received_at desc);
create index assessment_responses_question_idx on public.assessment_responses (question_id);

-- ---------------------------------------------------------------------------
-- RLS and privileges
-- ---------------------------------------------------------------------------
alter table public.assessment_questions enable row level security;
alter table public.assessment_attempts enable row level security;
alter table public.assessment_responses enable row level security;

revoke all on public.assessment_questions, public.assessment_attempts, public.assessment_responses
  from anon, authenticated;
grant select on public.assessment_questions, public.assessment_attempts, public.assessment_responses
  to authenticated;

create policy "questions: staff read"
  on public.assessment_questions for select to authenticated
  using ((select private.has_role('teacher')) or (select private.has_role('admin')));

create policy "attempts: owner reads own"
  on public.assessment_attempts for select to authenticated
  using (user_id = (select auth.uid()));

create policy "attempts: admin reads all"
  on public.assessment_attempts for select to authenticated
  using ((select private.has_role('admin')));

create policy "responses: owner reads own"
  on public.assessment_responses for select to authenticated
  using (user_id = (select auth.uid()));

create policy "responses: admin reads all"
  on public.assessment_responses for select to authenticated
  using ((select private.has_role('admin')));

-- ---------------------------------------------------------------------------
-- RPC: download published questions for a level, without answer keys.
-- Keyset pagination: pass the last id of the previous page as p_after.
-- ---------------------------------------------------------------------------
create function public.get_practice_questions(
  p_cefr_level public.cefr_level,
  p_after uuid default null,
  p_limit integer default 100
) returns table (
  id uuid,
  cefr_level public.cefr_level,
  skill text,
  prompt text,
  options text[],
  version integer,
  review_status text,
  updated_at timestamptz
)
language plpgsql stable security definer
set search_path = ''
as $$
#variable_conflict use_column
begin
  if auth.uid() is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;
  if not private.is_active_user() then
    raise exception 'account suspended' using errcode = '42501';
  end if;
  if p_limit is null or p_limit < 1 or p_limit > 200 then
    raise exception 'p_limit must be between 1 and 200' using errcode = '22023';
  end if;

  return query
    select q.id, q.cefr_level, q.skill, q.prompt, q.options, q.version, q.review_status, q.updated_at
      from public.assessment_questions q
     where q.cefr_level = p_cefr_level
       and q.status = 'published'
       and (p_after is null or q.id > p_after)
     order by q.id
     limit p_limit;
end;
$$;
revoke all on function public.get_practice_questions(public.cefr_level, uuid, integer) from public, anon;
grant execute on function public.get_practice_questions(public.cefr_level, uuid, integer) to authenticated;

-- ---------------------------------------------------------------------------
-- RPC: submit one practice answer. Idempotent on p_response_id.
-- ---------------------------------------------------------------------------
create function public.submit_practice_response(
  p_response_id uuid,
  p_attempt_id uuid,
  p_question_id uuid,
  p_chosen_option text,
  p_client_answered_at timestamptz default null
) returns table (
  response_id uuid,
  is_correct boolean,
  correct_option text,
  explanation text,
  received_at timestamptz,
  duplicate boolean
)
language plpgsql security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_uid uuid := auth.uid();
  v_question public.assessment_questions;
  v_attempt_owner uuid;
  v_existing public.assessment_responses;
  v_chosen text := upper(btrim(coalesce(p_chosen_option, '')));
  v_client_at timestamptz := p_client_answered_at;
  v_recent integer;
begin
  if v_uid is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;
  if not private.is_active_user() then
    raise exception 'account suspended' using errcode = '42501';
  end if;
  if p_response_id is null or p_attempt_id is null or p_question_id is null then
    raise exception 'response, attempt and question ids are required' using errcode = '22023';
  end if;
  if v_chosen !~ '^[A-F]$' then
    raise exception 'chosen option must be a single letter A-F' using errcode = '22023';
  end if;

  -- Replay of an already stored response: return the stored result.
  select * into v_existing from public.assessment_responses r where r.id = p_response_id;
  if found then
    if v_existing.user_id <> v_uid then
      raise exception 'response id belongs to another user' using errcode = '42501';
    end if;
    select q.correct_option, q.explanation into correct_option, explanation
      from public.assessment_questions q where q.id = v_existing.question_id;
    response_id := v_existing.id;
    is_correct := v_existing.is_correct;
    received_at := v_existing.received_at;
    duplicate := true;
    return next;
    return;
  end if;

  select count(*) into v_recent
    from public.assessment_responses r
   where r.user_id = v_uid and r.received_at > now() - interval '1 minute';
  if v_recent >= 120 then
    raise exception 'rate limit exceeded' using errcode = '54000';
  end if;

  select * into v_question from public.assessment_questions q where q.id = p_question_id;
  if not found or v_question.status <> 'published' then
    raise exception 'question not available' using errcode = '22023';
  end if;
  if ascii(v_chosen) - ascii('A') >= cardinality(v_question.options) then
    raise exception 'chosen option out of range' using errcode = '22023';
  end if;

  -- Client clocks are not trusted; drop timestamps more than 5 minutes in the future.
  if v_client_at is not null and v_client_at > now() + interval '5 minutes' then
    v_client_at := null;
  end if;

  insert into public.assessment_attempts (id, user_id, kind, cefr_level, client_started_at)
  values (p_attempt_id, v_uid, 'practice', v_question.cefr_level, v_client_at)
  on conflict (id) do nothing;

  select a.user_id into v_attempt_owner from public.assessment_attempts a where a.id = p_attempt_id;
  if v_attempt_owner <> v_uid then
    raise exception 'attempt belongs to another user' using errcode = '42501';
  end if;

  -- Same question already answered in this attempt under another id: first answer wins.
  select * into v_existing
    from public.assessment_responses r
   where r.attempt_id = p_attempt_id and r.question_id = p_question_id;
  if found then
    response_id := v_existing.id;
    is_correct := v_existing.is_correct;
    correct_option := v_question.correct_option;
    explanation := v_question.explanation;
    received_at := v_existing.received_at;
    duplicate := true;
    return next;
    return;
  end if;

  insert into public.assessment_responses
    (id, attempt_id, user_id, question_id, question_version, chosen_option, is_correct, client_answered_at)
  values
    (p_response_id, p_attempt_id, v_uid, p_question_id, v_question.version, v_chosen,
     v_chosen = v_question.correct_option, v_client_at)
  returning assessment_responses.received_at into received_at;

  perform private.log_event(v_uid, 'practice.response_submitted', 'assessment_response', p_response_id,
                            jsonb_build_object('attempt_id', p_attempt_id, 'cefr_level', v_question.cefr_level),
                            p_attempt_id);

  response_id := p_response_id;
  is_correct := v_chosen = v_question.correct_option;
  correct_option := v_question.correct_option;
  explanation := v_question.explanation;
  duplicate := false;
  return next;
end;
$$;
revoke all on function public.submit_practice_response(uuid, uuid, uuid, text, timestamptz) from public, anon;
grant execute on function public.submit_practice_response(uuid, uuid, uuid, text, timestamptz) to authenticated;

-- ---------------------------------------------------------------------------
-- RPC: per-level practice summary for the signed-in user (computed from stored rows).
-- ---------------------------------------------------------------------------
create function public.get_my_practice_summary()
returns table (cefr_level public.cefr_level, answered bigint, correct bigint)
language sql stable security invoker
set search_path = ''
as $$
  select a.cefr_level, count(*), count(*) filter (where r.is_correct)
    from public.assessment_responses r
    join public.assessment_attempts a on a.id = r.attempt_id
   where r.user_id = (select auth.uid())
   group by a.cefr_level
   order by a.cefr_level;
$$;
revoke all on function public.get_my_practice_summary() from public, anon;
grant execute on function public.get_my_practice_summary() to authenticated;
