#!/usr/bin/env python3
"""Build the driving-theory seed from content/theory/uk-theory-questions.json.

The source file groups questions by section and carries the question and its correct answer in
several languages; the app shows English with a Kurdish toggle, so only those two are imported.

Usage: python3 scripts/db/build_theory_seed.py
Writes backend/supabase/seed/theory_questions.sql (re-runnable: it updates drafts in place).
"""
from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "content" / "theory" / "uk-theory-questions.json"
TARGET = ROOT / "backend" / "supabase" / "seed" / "theory_questions.sql"

# The source numbers its sections; the database keys them by slug.
SLUGS = {
    "Alertness": "alertness",
    "Attitude": "attitude",
    "Safety & Your Vehicle": "safety-and-vehicle",
    "Safety Margins": "safety-margins",
    "Hazard Awareness": "hazard-awareness",
    "Vulnerable Road Users": "vulnerable-road-users",
    "Other Types of Vehicle": "other-vehicles",
    "Vehicle Handling": "vehicle-handling",
    "Motorway Rules": "motorway-rules",
    "Rules of the Road": "rules-of-the-road",
}


def sql(value: str | None) -> str:
    if value is None:
        return "null"
    text = " ".join(value.split())
    if not text:
        return "null"
    return "'" + text.replace("'", "''") + "'"


def main() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    rows: list[str] = []
    per_section: dict[str, int] = {}

    for section in data["sections"]:
        slug = SLUGS.get(section["category"])
        if slug is None:
            raise SystemExit(f"unknown section {section['category']!r}; add it to SLUGS")
        for position, question in enumerate(section["questions"], start=1):
            prompt = " ".join(question["questionEn"].split())
            answer = " ".join(question["correctAnswer"].split())
            if not prompt or not answer:
                raise SystemExit(f"{slug} #{question['id']} has an empty question or answer")
            rows.append(
                "  ("
                f"'theory:{slug}:{question['id']}',"
                f"(select id from public.theory_sections where slug = '{slug}'),"
                f"{position},"
                f"{sql(prompt)},"
                f"{sql(question.get('questionKu'))},"
                f"{sql(answer)},"
                f"{sql(question.get('correctAnswerKu'))},"
                "'draft',"
                "'content:uk-theory-questions'"
                ")"
            )
            per_section[slug] = per_section.get(slug, 0) + 1

    header = [
        f"-- GENERATED by scripts/db/build_theory_seed.py from {SOURCE.relative_to(ROOT)} — do not edit by hand.",
        f"-- {len(rows)} driving-theory questions in {len(per_section)} sections:",
        "--   " + ", ".join(f"{slug} {count}" for slug, count in sorted(per_section.items())),
        "-- Imported as drafts, so a teacher publishes them (staff_publish_theory_drafts) when they are checked.",
        "insert into public.theory_questions",
        "  (external_ref, section_id, sort_order, prompt, prompt_ckb, answer, answer_ckb, status, source)",
        "values",
    ]
    footer = [
        "on conflict (external_ref) do update set",
        "  section_id = excluded.section_id, sort_order = excluded.sort_order,",
        "  prompt = excluded.prompt, prompt_ckb = excluded.prompt_ckb,",
        "  answer = excluded.answer, answer_ckb = excluded.answer_ckb",
        "-- Only untouched imports are refreshed; anything a teacher has published stays as it is.",
        "where public.theory_questions.status = 'draft';",
    ]
    TARGET.write_text("\n".join(header) + "\n" + ",\n".join(rows) + "\n" + "\n".join(footer) + "\n", encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(rows)} questions")


if __name__ == "__main__":
    main()
